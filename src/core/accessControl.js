export function normalizeAccessRole(role) {
  return ROLE_ALIASES[normalizeToken(role)] || ACCESS_ROLES.READ_ONLY
}

export function canForRole(role, capability) {
  if (!capability) return true
  return ROLE_CAPABILITIES[normalizeAccessRole(role)]?.has(capability) === true
}

export function getAccessPolicy(role) {
  const normalizedRole = normalizeAccessRole(role)
  return Object.freeze({
    role: normalizedRole,
    manageStaff: canForRole(normalizedRole, ACCESS_CAPABILITIES.STAFF_MANAGE),
    manageTeam: canForRole(normalizedRole, ACCESS_CAPABILITIES.TEAM_IDENTITY_UPDATE),
    mutateSport: canForRole(normalizedRole, ACCESS_CAPABILITIES.SPORT_MUTATE),
  })
}

export function canAccessSectionForRole(role, sectionKey) {
  if (!(sectionKey in SECTION_CAPABILITY)) return false
  return canForRole(role, SECTION_CAPABILITY[sectionKey])
}

export function filterMenuForRole(menu, role) {
  return menu.filter(([sectionKey]) => canAccessSectionForRole(role, sectionKey))
}

export function firstAccessibleSection(menu, role, preferred = 'dashboard') {
  if (canAccessSectionForRole(role, preferred)) return preferred
  return filterMenuForRole(menu, role)[0]?.[0] || 'profile'
}
